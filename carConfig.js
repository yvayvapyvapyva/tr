/* ============================================================
   СХЕМА ОКНА НАСТРОЕК — что и как можно редактировать
   Движок: get/set по пути через mutable-объекты/массивы.
   ============================================================ */

const _roots=()=>({ CAR, PHYS, GEAR_RATIO, TQ_CURVE, GATE_X, ROW_Y });

export function cfgGet(path){
  const _r=_roots();
  const p = String(path).split('.');
  let o = _r[p[0]];
  for(let i=1;i<p.length;i++) o = o[p[i]];
  return o;
}
export function cfgSet(path, v){
  const _r=_roots();
  const p = String(path).split('.');
  let o = _r[p[0]];
  for(let i=1;i<p.length-1;i++) o = o[p[i]];
  o[p[p.length-1]] = v;
}

